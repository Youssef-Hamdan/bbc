const EXT_PREF = ["webp", "jpg", "jpeg", "png"] as const;

export function resolveProjectImage(name: string): string | undefined {
  const base = name.split("/").pop()?.trim();
  if (!base) return undefined;
  if (PROJECT_FILES.has(base)) return `/project-4/${base}`;
  const stem = base.replace(/\.[^.]+$/, "");
  for (const ext of EXT_PREF) {
    const candidate = `${stem}.${ext}`;
    if (PROJECT_FILES.has(candidate)) return `/project-4/${candidate}`;
  }
  return undefined;
}

export function resolveProjectImages(names: string[], fallback: string[] = []): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const name of [...names, ...fallback]) {
    const path = resolveProjectImage(name);
    if (path && !seen.has(path)) {
      seen.add(path);
      out.push(path);
    }
  }
  return out;
}
